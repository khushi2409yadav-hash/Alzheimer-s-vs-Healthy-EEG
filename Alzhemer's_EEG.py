from sklearn.linear_model import LogisticRegression         # model 1
from sklearn.svm import SVC                                 # model 2 (SVM)
from sklearn.ensemble import RandomForestClassifier         # model 3
from sklearn.model_selection import RepeatedStratifiedKFold, StratifiedKFold, cross_val_score, cross_val_predict   # testing tools

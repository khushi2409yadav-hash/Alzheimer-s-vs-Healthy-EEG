# Defines a function that reads one person's EEG and returns the numbers the model learns from.
# It does not run on anyone yet. Cell 5 uses it.

BANDS = {"delta": (0.5, 4), "theta": (4, 8), "alpha": (8, 13), "beta": (13, 30)}   # wave types and their speeds in Hz
REGIONS = {                      # the 19 electrodes grouped into 5 brain areas
    "frontal":   ["Fp1", "Fp2", "F7", "F3", "Fz", "F4", "F8"],
    "central":   ["C3", "Cz", "C4"],
    "temporal":  ["T3", "T4", "T5", "T6"],
    "parietal":  ["P3", "Pz", "P4"],
    "occipital": ["O1", "O2"],
}

def get_features(path):
    # 1) read the recording, keep only 0.5-45 Hz (removes slow drift and fast noise), lower the sampling rate to 250 Hz
    raw = mne.io.read_raw_eeglab(path, preload=True)
    raw.filter(0.5, 45.0)
    raw.resample(250)
    names = [n.lower() for n in raw.ch_names]

    # 2) power at each frequency, for every electrode
    #    (Welch cuts the signal into 4 second pieces and averages them, which gives a steadier result)
    freqs, psd = welch(raw.get_data(), fs=250, nperseg=1000)
    total = (freqs >= 0.5) & (freqs < 45)                          # the frequency range we care about

    # 3) for each brain area and wave type: what SHARE of the total power is this wave? (20 numbers)
    f = {}
    for region, chans in REGIONS.items():
        rows = [names.index(c.lower()) for c in chans]
        p = psd[rows].mean(axis=0)                                 # average the electrodes of this area
        for band, (lo, hi) in BANDS.items():
            in_band = (freqs >= lo) & (freqs < hi)
            f[f"{region}_{band}"] = p[in_band].sum() / p[total].sum()   # a share, so loud and quiet recordings can be compared

    # 4) two "slowing" numbers: higher means slower brain waves, which is linked to Alzheimer's (2 numbers)
    f["theta_alpha_ratio"] = np.mean([f[f"{r}_theta"] / f[f"{r}_alpha"] for r in REGIONS])
    f["slowing_ratio"] = np.mean([(f[f"{r}_delta"] + f[f"{r}_theta"]) /
                                  (f[f"{r}_alpha"] + f[f"{r}_beta"]) for r in REGIONS])

    # 5) how fast is the strongest alpha wave at the back of the head? (1 number)
    back = [names.index(c.lower()) for c in REGIONS["parietal"] + REGIONS["occipital"]]
    p_back = psd[back].mean(axis=0)
    alpha_range = (freqs >= 6) & (freqs <= 13)
    f["alpha_peak_freq"] = freqs[alpha_range][np.argmax(p_back[alpha_range])]

    # also keep this person's average spectrum, only for the plot in cell 6
    spectrum = psd.mean(axis=0)[total] / psd.mean(axis=0)[total].sum()
    return f, freqs[total], spectrum

# Loops over every person, builds their 23 numbers, and puts them into one table
rows, spectra = [], []
for _, r in df.iterrows():
    path = glob.glob(f"ds004504/derivatives/{r['participant_id']}/eeg/*.set")[0]    # find this person's file
    f, freqs_used, spectrum = get_features(path)
    rows.append(f)
    spectra.append(spectrum)
    print(r["participant_id"], "done")

X = pd.DataFrame(rows)                                # one row per person, 23 columns
y = (df["Group"] == "A").astype(int).values           # answers: 1 = Alzheimer's, 0 = healthy
spectra = np.array(spectra)
print(X.shape)                                        # should be (65, 23)
print(X.groupby(y)[["theta_alpha_ratio", "slowing_ratio", "alpha_peak_freq"]].mean().round(3))   # group averages (0 = healthy, 1 = Alzheimer's)

# Plots how much power each group has at each frequency, so you can see any difference
plt.plot(freqs_used, spectra[y == 0].mean(axis=0), label="Healthy")
plt.plot(freqs_used, spectra[y == 1].mean(axis=0), label="Alzheimer's")
plt.xlim(0.5, 30)
plt.yscale("log")                                     # log scale makes small differences easier to see
plt.xlabel("Frequency (Hz)")
plt.ylabel("Share of total power")
plt.title("Average EEG spectrum")
plt.legend()
plt.savefig("alz_spectrum.png", dpi=150, bbox_inches="tight")     # saves the picture for GitHub
plt.show()

# One row = one person, so every test below is on people that were not used for training
models = {
    "Logistic regression": LogisticRegression(C=0.1, max_iter=2000),
    "SVM": SVC(C=1.0),
    "Random forest": RandomForestClassifier(n_estimators=200, max_depth=3, random_state=0),
}
# 5-fold: split the 65 people into 5 groups, train on 4, test on the 1 left out, repeat for each group.
# Then do the whole thing 10 times with different splits and average the scores.
cv = RepeatedStratifiedKFold(n_splits=5, n_repeats=10, random_state=0)

print("Always guessing the bigger group:", round(max(y.mean(), 1 - y.mean()), 3))     # reference score for comparison
for name, model in models.items():
    scores = cross_val_score(make_pipeline(StandardScaler(), model), X, y, cv=cv)
    print(f"{name}: accuracy {scores.mean():.3f} (+/- {scores.std():.3f})")           # +/- shows how much the score changes between splits

# Shows how many people of each group were predicted correctly and how many were mixed up.
# Change the model name below if another model scored best.
best = "Logistic regression"
pred = cross_val_predict(make_pipeline(StandardScaler(), models[best]), X, y,
                         cv=StratifiedKFold(5, shuffle=True, random_state=0))    # every prediction is on a person left out of training
ConfusionMatrixDisplay.from_predictions(y, pred, display_labels=["Healthy", "Alzheimer's"], cmap="Blues")
plt.title(best)
plt.savefig("alz_confusion_matrix.png", dpi=150, bbox_inches="tight")             # saves the picture for GitHub
plt.show()


SFREQ = 250                 # samples per second
EPOCH_SEC = 20              # length of each piece we cut
NPERSEG = 4 * SFREQ         # welch window = 4 seconds
BANDS = {"delta": (0.5, 4), "theta": (4, 8), "alpha": (8, 13), "beta": (13, 30)}   # wave types in Hz
REGIONS = {                 # 19 electrodes grouped into 5 brain areas
    "frontal":   ["Fp1", "Fp2", "F7", "F3", "Fz", "F4", "F8"],
    "central":   ["C3", "Cz", "C4"],
    "temporal":  ["T3", "T4", "T5", "T6"],
    "parietal":  ["P3", "Pz", "P4"],
    "occipital": ["O1", "O2"],
}
PAIRS = list(itertools.combinations(REGIONS.keys(), 2))   # all 10 region pairs (for coherence)
FREQS = np.fft.rfftfreq(NPERSEG, 1 / SFREQ)               # frequencies welch will give
TOTAL = (FREQS >= 0.5) & (FREQS < 45)                     # range we care about
FREQ_USED = FREQS[TOTAL]

def load_clean(path):
    # read one person's EEG and prepare it
    raw = mne.io.read_raw_eeglab(path, preload=True)
    raw.filter(0.5, 45.0)       # remove slow drift and fast noise
    raw.resample(SFREQ)         # same speed for everyone
    return raw.get_data(), [n.lower() for n in raw.ch_names]


def features_for_epoch(ep, names):
    # turns ONE 20 s piece into 33 numbers for the model
    freqs, psd = welch(ep, fs=SFREQ, nperseg=NPERSEG)
    f, region_signal = {}, {}

    # relative band power per region (20 numbers)
    for region, chans in REGIONS.items():
        rows = [names.index(c.lower()) for c in chans]
        p = psd[rows].mean(axis=0)
        region_signal[region] = ep[rows].mean(axis=0)
        for band, (lo, hi) in BANDS.items():
            m = (freqs >= lo) & (freqs < hi)
            f[f"{region}_{band}"] = p[m].sum() / p[TOTAL].sum()

    # slowing ratios (higher = slower brain waves) (2 numbers)
    f["theta_alpha_ratio"] = np.mean([f[f"{r}_theta"] / f[f"{r}_alpha"] for r in REGIONS])
    f["slowing_ratio"] = np.mean([(f[f"{r}_delta"] + f[f"{r}_theta"]) /
                                  (f[f"{r}_alpha"] + f[f"{r}_beta"]) for r in REGIONS])

    # alpha peak frequency at the back of the head (1 number)
    back = [names.index(c.lower()) for c in REGIONS["parietal"] + REGIONS["occipital"]]
    p_back = psd[back].mean(axis=0)
    ar = (freqs >= 6) & (freqs <= 13)
    f["alpha_peak_freq"] = freqs[ar][np.argmax(p_back[ar])]

    # alpha coherence between region pairs (10 numbers)
    for a, b in PAIRS:
        fc, coh = coherence(region_signal[a], region_signal[b], fs=SFREQ, nperseg=NPERSEG)
        f[f"coh_alpha_{a}_{b}"] = coh[(fc >= 8) & (fc < 13)].mean()

    spec = psd.mean(axis=0)[TOTAL]          # average spectrum, only for the plot later
    return f, spec / spec.sum()


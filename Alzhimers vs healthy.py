def bh_fdr(p):
    # correction for testing many features at once (avoids false "significant" results)
    p = np.asarray(p); n = len(p); order = np.argsort(p)
    adj = p[order] * n / np.arange(1, n + 1)
    adj = np.minimum.accumulate(adj[::-1])[::-1]
    out = np.empty(n); out[order] = np.minimum(adj, 1)
    return out


# test every feature: is it different between the two groups?
rows = []
for c in FEATURES:
    a, h = X.loc[y == 1, c], X.loc[y == 0, c]
    rows.append((c, h.median(), a.median(), mannwhitneyu(a, h).pvalue))
stats = pd.DataFrame(rows, columns=["feature", "healthy_median", "alz_median", "p"])
stats["p_fdr"] = bh_fdr(stats["p"])
stats = stats.sort_values("p").reset_index(drop=True)
print(stats.head(10).round(4))
print("Significant after correction (q < 0.05):", int((stats["p_fdr"] < 0.05).sum()))
results["n_significant_features"] = int((stats["p_fdr"] < 0.05).sum())

# effect size (Cohen's d) per brain area and wave type: red = higher in Alzheimer's, blue = lower
